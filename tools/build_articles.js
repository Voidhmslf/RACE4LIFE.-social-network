// Собирает content/*.js в единый articles.js (запуск: node tools/build_articles.js)
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'content');
const parts = fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort()
  .map(f => fs.readFileSync(path.join(dir, f), 'utf8'));
fs.writeFileSync(path.join(__dirname, '..', 'articles.js'), '/* AUTO-GENERATED by build_articles.js — не править вручную */\n' + parts.join('\n'));
console.log('articles.js собран из', parts.length, 'файлов');
